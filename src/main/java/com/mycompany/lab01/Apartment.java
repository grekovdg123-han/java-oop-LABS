public class Apartment{
    private long id;
    private String address;
    private double area;
    private int rooms;
    private double price;
    
    
    public long getId(){
        return id;
    }
    
    public String getAddress(){
        return address;
    }
    
    public double getArea(){
        return area;
    }
    
    public int getRooms(){
        return rooms;
    }
    
    public double getPrice(){
        return price;
    }
    
}
